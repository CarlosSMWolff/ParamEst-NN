"""
Repair the training trajectories published on Zenodo, which were generated by the
buggy version of `QuantumModel.simulateTrajectoryFixedJumps`.

The bug
-------
`simulateTrajectoryFixedJumps` simulates a stretch of time of length

    tf = factor * njumps / n_expect,        n_expect = <J^dag J>_ss,

in which `factor * njumps` jumps are expected on average. When a stretch happened
to contain fewer than `njumps` jumps, the simulation was continued from its final
state, and the buggy version made two mistakes when stitching the stretches
together:

* it converted the jump times of each stretch to time delays *separately*, and
  `to_time_delay` reads its first entry as a delay measured from zero. That only
  holds for the very first stretch, so the opening delay of every continuation was
  recorded as an absolute time instead of a delay;
* it offset each continuation by the time of the *last jump* of the previous
  stretch rather than by the length of that stretch, which drops the interval
  between that last jump and the end of the stretch.

The net effect is a single, spuriously large time delay at the position where the
continuation starts. About 9% of the 48-jump trajectories on Zenodo take a
continuation and therefore carry one.

The repair
----------
Both mistakes are deterministic, so no information was lost and the trajectories
can be repaired exactly rather than regenerated. Write `S` for the true absolute
time of the last jump of a stretch, `tf` for the stretch length and `c` for the
first jump time inside the continuation. The buggy code recorded

    recorded = tshift + c,      tshift = sum of the last-jump times of all
                                        previous stretches,

whereas the correct delay, measured from the previous jump, is

    correct  = (segment_index * tf + c) - S.

`tf` is fixed by the parameters of the trajectory, which are published alongside
it, and `S` and `tshift` follow from the delays that precede the continuation, so
`correct` is recoverable from `recorded`. For the common case of a single
continuation this collapses to `correct = recorded + tf - 2 * S`.

Finding the continuations is exact as well: every jump of stretch `j` happened
before `(j + 1) * tf` by construction, so the first cumulative time that exceeds
`(j + 1) * tf` is necessarily a corrupted entry and nothing else can be. The
recovered `c` then has to be a jump time inside the continuation, which is what
makes a second run on an already repaired file a no-op rather than a disaster.

Usage
-----
    python scripts/fix_zenodo_trajectories.py --help
    python scripts/fix_zenodo_trajectories.py --dry_run          # report only
    python scripts/fix_zenodo_trajectories.py                    # repair in place

By default the originals are kept next to the repaired files under the suffix
`.zenodo-orig.npy`, so a run can always be undone and re-checked.
"""

import shutil
from pathlib import Path
from typing import Any, Dict, Optional, Tuple

import fire
import numpy as np

# The datasets published on Zenodo that `simulateTrajectoryFixedJumps` produced,
# as (trajectories, parameters) relative to `datapath`. The validation sets are
# not listed: they were generated by a different loop in
# `1-Trajectories_generation.ipynb`, which restarts every continuation from the
# ground state instead of stitching stretches, and so is not affected.
DATASETS = {
    "2d": (
        "training-trajectories/2D-delta-omega/taus-2D.npy",
        "training-trajectories/2D-delta-omega/param_rand_list-2D.npy",
    ),
    "1d": (
        "training-trajectories/1D-delta/taus-Delta-1D.npy",
        "training-trajectories/1D-delta/delta_rand_list-Delta-1D.npy",
    ),
}

# Suffix under which the untouched Zenodo file is kept when repairing in place
BACKUP_SUFFIX = ".zenodo-orig.npy"

# `simulateTrajectoryFixedJumps` hard-codes this safety margin on the length of
# each simulated stretch, and `1-Trajectories_generation.ipynb` used the default.
FACTOR = 1.2

# A cumulative time is only taken to be corrupted when it exceeds the end of its
# stretch by more than this relative amount. The corrupted entries overshoot by
# of order `tf` itself, so this only guards against rounding in the cumulative
# sums, and no plausible value of it changes the outcome.
RTOL = 1e-9


def steady_state_rate(
    delta: np.ndarray, omega: np.ndarray, gamma: float = 1.0
) -> np.ndarray:
    """Photon emission rate of a coherently driven two-level system in the steady
    state, `n_expect = <J^dag J>_ss = gamma * rho_ee`.

    This is the closed form of the `steadystate` + `expect` pair that
    `simulateTrajectoryFixedJumps` evaluates. It reproduces `qutip` to machine
    precision and is the same expression as `compute_population_ss`.

    Args:
        delta (np.ndarray): Detuning of the drive.
        omega (np.ndarray): Drive amplitude.
        gamma (float): Spontaneous emission rate, which sets the time scale.

    Returns:
        np.ndarray: The steady-state emission rate, elementwise.
    """
    return gamma * 4 * omega**2 / (gamma**2 + 4 * delta**2 + 8 * omega**2)


def segment_length(
    delta: np.ndarray,
    omega: np.ndarray,
    njumps: int,
    gamma: float = 1.0,
    factor: float = FACTOR,
) -> np.ndarray:
    """Length `tf` of a single simulated stretch, as chosen by the simulator.

    Args:
        delta (np.ndarray): Detuning of the drive.
        omega (np.ndarray): Drive amplitude.
        njumps (int): Number of time delays the simulator was asked for.
        gamma (float): Spontaneous emission rate.
        factor (float): Safety margin applied to the expected number of jumps.

    Returns:
        np.ndarray: The stretch length of every trajectory.
    """
    return factor * njumps / steady_state_rate(delta, omega, gamma)


def repair_chunk(
    taus: np.ndarray, tf: np.ndarray
) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Repair the corrupted opening delays of a block of trajectories.

    The scan below walks the delays left to right while tracking, per trajectory,
    the true absolute time `T` of the last jump seen, the index `seg` of the
    stretch it belongs to, and the offset `tshift` the buggy code would have added
    to that stretch. A delay is corrupted exactly when it pushes the absolute time
    past the end of its stretch, since the simulator never integrated beyond it.

    Repairing an already repaired array would destroy it, because a repaired
    trajectory legitimately runs past the end of its first stretch. The recovered
    `c` is what tells the two apart: for a corrupted delay it is a jump time
    inside the continuation and so lies in `(0, tf]`, whereas re-reading a
    repaired delay yields a negative `c`. Such delays are left untouched and
    counted separately, so a second run reports that there is nothing to do
    instead of silently corrupting the data.

    Args:
        taus (np.ndarray): Trajectories of shape (n, njumps). Not modified.
        tf (np.ndarray): Stretch length of each trajectory, shape (n,).

    Returns:
        tuple(np.ndarray, np.ndarray, np.ndarray): The repaired trajectories, an
        integer array with the number of corrupted delays repaired in each
        trajectory, and a boolean array marking trajectories that cross a stretch
        boundary but do not look corrupted, i.e. that were already repaired.
    """
    out = np.array(taus, dtype=np.float64, copy=True)
    n, njumps = out.shape

    T = np.zeros(n)  # true absolute time of the last jump processed
    seg = np.zeros(n, dtype=np.int64)  # stretch that jump belongs to
    tshift = np.zeros(n)  # offset the buggy code added to that stretch
    repaired = np.zeros(n, dtype=np.int64)
    suspect = np.zeros(n, dtype=bool)

    for k in range(njumps):
        cand = T + out[:, k]
        # A genuine jump of stretch `seg` occurred before the stretch ended.
        crossing = cand > (seg + 1) * tf * (1 + RTOL)

        if crossing.any():
            # `T - seg * tf` is the last jump time measured inside its own
            # stretch, which is what the buggy code accumulated into `tshift`.
            tshift_new = tshift + (T - seg * tf)
            # Undo the offset to recover the first jump time of the continuation
            c = out[:, k] - tshift_new
            # ... which has to be a time inside the continuation to be credible.
            bad = crossing & (c > 0) & (c <= tf)
            suspect |= crossing & ~bad

            seg[bad] += 1
            tshift[bad] = tshift_new[bad]
            # Re-measure the delay from the previous jump, in absolute time.
            cand[bad] = seg[bad] * tf[bad] + c[bad]
            out[bad, k] = cand[bad] - T[bad]
            repaired[bad] += 1

        T = cand

    return out, repaired, suspect


def _report(name: str, values: np.ndarray, fmt: str = ".6f") -> str:
    """Format a small five-number summary of an array for the run log."""
    if values.size == 0:
        return f"  {name}: (empty)"
    q = np.quantile(values, [0.0, 0.5, 1.0])
    return (
        f"  {name}: min={q[0]:{fmt}} median={q[1]:{fmt}} max={q[2]:{fmt}} "
        f"mean={values.mean():{fmt}}"
    )


def fix_dataset(
    taus_path: Path,
    params_path: Path,
    out_path: Optional[Path],
    gamma: float = 1.0,
    factor: float = FACTOR,
    chunk_size: int = 250_000,
    dry_run: bool = False,
) -> Dict[str, Any]:
    """Check one published dataset for the bug and, unless `dry_run`, repair it.

    Args:
        taus_path (Path): The published trajectories.
        params_path (Path): The parameters they were simulated from. Either an
            (n, 2) array of (delta, omega) pairs, or an (n,) array of detunings
            for the 1D dataset, whose drive amplitude was fixed to one.
        out_path (Optional[Path]): Where the repaired trajectories go. When None
            the file is repaired in place.
        gamma (float): Spontaneous emission rate used to generate the data.
        factor (float): Safety margin used to generate the data.
        chunk_size (int): Number of trajectories held in memory at a time.
        dry_run (bool): Only report what would be repaired.

    Returns:
        dict: Counts and summary statistics of the run.
    """
    params = np.load(params_path, mmap_mode="r")
    taus = np.load(taus_path, mmap_mode="r")
    n, njumps = taus.shape
    assert len(params) == n, "parameters and trajectories have different lengths"

    print(f"\n=== {taus_path} ===")
    print(f"{n} trajectories of {njumps} jumps, parameters {params.shape}")

    source = taus_path
    if not dry_run:
        if out_path is None:
            # Move the original aside and stream from it, so the repaired file is
            # never read back as if it were the input.
            source = taus_path.with_suffix(BACKUP_SUFFIX)
            if source.exists():
                raise FileExistsError(
                    f"{source} already exists: this dataset looks repaired "
                    f"already. Restore it over {taus_path} to run again."
                )
            print(f"keeping the original as {source.name}")
            shutil.move(taus_path, source)
            out_path = taus_path
            taus = np.load(source, mmap_mode="r")
        else:
            if out_path.resolve() == taus_path.resolve():
                raise ValueError(
                    f"--outdir points at {taus_path.parent}, which would "
                    f"overwrite {taus_path.name} while it is being read. Drop "
                    f"--outdir to repair in place, which keeps the original."
                )
            out_path.parent.mkdir(parents=True, exist_ok=True)
        out = np.lib.format.open_memmap(
            out_path, mode="w+", dtype=np.float64, shape=(n, njumps)
        )
    else:
        out = None

    n_affected = 0
    n_multi = 0
    n_over = 0
    n_suspect = 0
    ratio_before, ratio_after, seg0_frac = [], [], []

    for start in range(0, n, chunk_size):
        stop = min(start + chunk_size, n)
        p = np.asarray(params[start:stop], dtype=np.float64)
        if p.ndim == 1:  # 1D dataset: only delta was sampled, omega was 1
            delta, omega = p, np.ones_like(p)
        else:
            delta, omega = p[:, 0], p[:, 1]
        tf = segment_length(delta, omega, njumps, gamma, factor)

        block = np.asarray(taus[start:stop], dtype=np.float64)
        fixed, repaired, suspect = repair_chunk(block, tf)

        hit = repaired > 0
        n_affected += int(hit.sum())
        n_multi += int((repaired > 1).sum())
        n_suspect += int(suspect.sum())
        ratio_before.append(block.sum(axis=1) / tf)
        elapsed = fixed.sum(axis=1)
        ratio_after.append(elapsed / tf)
        # A trajectory that took `repaired` continuations ran over
        # `repaired + 1` stretches, so that is the bound its total must respect.
        # A trajectory flagged as already repaired took at least one, and its
        # own crossings are the count of stretches it used.
        stretches = repaired + 1 + suspect * np.ceil(elapsed / tf - 1).astype(int)
        n_over += int((elapsed > stretches * tf * (1 + RTOL)).sum())
        if hit.any():
            # Position of the first repair, i.e. the number of jumps the first
            # stretch produced, as a fraction of the njumps that were asked for.
            first = np.argmax(fixed != block, axis=1)[hit]
            seg0_frac.append(first / njumps)

        if out is not None:
            out[start:stop] = fixed
        print(f"  {stop}/{n} trajectories, {n_affected} repaired so far", end="\r")

    if out is not None:
        out.flush()
        del out

    ratio_before = np.concatenate(ratio_before)
    ratio_after = np.concatenate(ratio_after)
    seg0 = np.concatenate(seg0_frac) if seg0_frac else np.array([])

    # For a renewal process the mean delay is 1/n_expect, so the total elapsed
    # time of njumps delays averages to njumps/n_expect = tf/factor. That is an
    # exact, parameter-free target and the sharpest check that the repair landed.
    target = 1.0 / factor
    print(" " * 70, end="\r")
    print(f"affected trajectories: {n_affected}/{n} ({n_affected / n:.4%})")
    print(f"  of which more than one continuation: {n_multi}")
    if n_suspect:
        print(
            f"  {n_suspect} trajectories cross a stretch boundary without looking "
            f"corrupted, and were left alone.\n"
            f"  That is what an already repaired file looks like: check that "
            f"{taus_path.name} is the file as published."
        )
    if seg0.size:
        print(_report("first stretch length / njumps", seg0, ".4f"))
    print("total elapsed time / tf:")
    print(_report("before", ratio_before))
    print(_report("after ", ratio_after))
    print(
        f"  ensemble mean after repair: {ratio_after.mean():.6f} "
        f"(expected 1/factor = {target:.6f}, "
        f"off by {abs(ratio_after.mean() - target) / target:.3%}; "
        f"before repair it was {ratio_before.mean():.6f}, "
        f"off by {abs(ratio_before.mean() - target) / target:.3%})"
    )
    # A repaired trajectory legitimately runs past tf, since it spans more than
    # one stretch; what must hold is that it stays within the stretches it used.
    print(f"  trajectories exceeding the stretches they used: {n_over}")

    return {
        "file": str(taus_path),
        "n_trajectories": int(n),
        "n_affected": int(n_affected),
        "n_multiple_continuations": int(n_multi),
        "fraction_affected": float(n_affected / n),
        "mean_elapsed_over_tf_before": float(ratio_before.mean()),
        "mean_elapsed_over_tf_after": float(ratio_after.mean()),
        "expected_mean_elapsed_over_tf": float(target),
        "n_over_available_stretches_after": n_over,
        "n_suspect_already_repaired": n_suspect,
    }


def main(
    datapath: str = "data/",
    dataset: str = "both",
    outdir: Optional[str] = None,
    gamma: float = 1.0,
    factor: float = FACTOR,
    chunk_size: int = 250_000,
    dry_run: bool = False,
) -> None:
    """Check the published training trajectories for the stitching bug of
    `simulateTrajectoryFixedJumps` and repair the corrupted time delays.

    Args:
        datapath (str): Root folder holding the downloaded Zenodo data.
        dataset (str): Which dataset to process: "2d", "1d" or "both".
        outdir (Optional[str]): Write the repaired trajectories here instead of
            repairing in place, under their original file names.
        gamma (float): Spontaneous emission rate used to generate the data.
        factor (float): Safety margin used to generate the data. This is the
            `factor` of `simulateTrajectoryFixedJumps` and must match the value
            the data was generated with, otherwise nothing can be repaired.
        chunk_size (int): Number of trajectories held in memory at a time.
        dry_run (bool): Report what is affected without writing anything.
    """
    root = Path(datapath)
    names = list(DATASETS) if dataset == "both" else [dataset]
    unknown = [x for x in names if x not in DATASETS]
    if unknown:
        raise ValueError(f"Unknown dataset {unknown}, pick from {list(DATASETS)}")

    results = []
    for name in names:
        rel_taus, rel_params = DATASETS[name]
        taus_path = root / rel_taus
        params_path = root / rel_params
        if not taus_path.is_file() or not params_path.is_file():
            print(f"\n=== {name} ===\nskipped, {taus_path} not found")
            continue
        out_path = None if outdir is None else Path(outdir) / Path(rel_taus).name
        results.append(
            fix_dataset(
                taus_path,
                params_path,
                out_path,
                gamma=gamma,
                factor=factor,
                chunk_size=chunk_size,
                dry_run=dry_run,
            )
        )

    if dry_run:
        print("\ndry run: nothing was written")
    return


if __name__ == "__main__":
    fire.Fire(main)
